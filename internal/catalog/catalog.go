// Package catalog reads the table metadata that every stage needs from a PostgreSQL system catalog:
// which tables are migrated, their columns, replica identity and the format used to copy them.
package catalog

import (
	"context"
	"fmt"

	"github.com/shinession/gophant/internal/config"
	"github.com/shinession/gophant/internal/pg"
)

// Relation kinds (pg_class.relkind) that carry data.
const (
	KindTable       = 'r'
	KindPartitioned = 'p'
)

// Replica identity values (pg_class.relreplident).
const (
	ReplicaDefault = 'd'
	ReplicaNothing = 'n'
	ReplicaFull    = 'f'
	ReplicaIndex   = 'i'
)

// Column is one live column of a table.
type Column struct {
	Name     string
	TypeOID  uint32
	TypeName string
	// Generated is 0 for a plain column, 's' for a stored and 'v' for a virtual generated column.
	Generated byte
	// Identity is 0 for a plain column, 'a' for GENERATED ALWAYS and 'd' for GENERATED BY DEFAULT AS IDENTITY.
	Identity byte
	NotNull  bool
}

// CopyFormat is the COPY wire format used to move a table.
type CopyFormat string

// The two formats. Binary is the default; text is the fallback for tables whose column types
// cannot be moved in binary between two different databases (see BinarySafe).
const (
	FormatBinary CopyFormat = "BINARY"
	FormatText   CopyFormat = "TEXT"
)

// Table is one table of the migration scope.
type Table struct {
	OID         uint32
	Schema      string
	Name        string
	Kind        byte
	IsPartition bool
	// Persistence is 'p' for a permanent and 'u' for an UNLOGGED table.
	Persistence  byte
	ReplicaIdent byte
	HasPK        bool
	// HasReplicaIndex tells whether an index is marked as the replica identity (indisreplident).
	HasReplicaIndex bool
	EstimatedRows   int64
	TotalBytes      int64

	Columns    []Column
	CopyFormat CopyFormat
}

// FullName returns schema.name without quoting, for messages.
func (t Table) FullName() string { return t.Schema + "." + t.Name }

// Quoted returns the quoted, schema-qualified name for SQL.
func (t Table) Quoted() string { return pg.Qualified(t.Schema, t.Name) }

// IsPhysical reports whether the table holds its own rows: ordinary tables and the leaf partitions
// that are ordinary tables. Partitioned parents hold no rows themselves.
func (t Table) IsPhysical() bool { return t.Kind == KindTable }

// CopyColumns returns the columns that take part in COPY and replay: every column except the
// generated ones, which the target computes itself.
func (t Table) CopyColumns() []Column {
	cols := make([]Column, 0, len(t.Columns))
	for _, c := range t.Columns {
		if c.Generated == 0 {
			cols = append(cols, c)
		}
	}
	return cols
}

// ColumnNames returns the names of CopyColumns.
func (t Table) ColumnNames() []string {
	cols := t.CopyColumns()
	names := make([]string, len(cols))
	for i, c := range cols {
		names[i] = c.Name
	}
	return names
}

const listTablesSQL = `
SELECT c.oid::bigint,
       n.nspname,
       c.relname,
       c.relkind::text,
       c.relispartition,
       c.relpersistence::text,
       c.relreplident::text,
       EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid = c.oid AND i.indisprimary),
       EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid = c.oid AND i.indisreplident),
       GREATEST(c.reltuples, 0)::bigint,
       pg_total_relation_size(c.oid)
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ('r', 'p')
  AND n.nspname NOT IN ('pg_catalog', 'information_schema')
  AND n.nspname NOT LIKE 'pg\_toast%'
  AND n.nspname NOT LIKE 'pg\_temp\_%'
  AND c.relpersistence <> 't'
  AND ($1::text[] IS NULL OR n.nspname = ANY ($1))
  -- Tables that belong to an extension are created by CREATE EXTENSION on the target.
  AND NOT EXISTS (SELECT 1 FROM pg_depend d
                  WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid AND d.deptype = 'e')
ORDER BY n.nspname, c.relname`

// ListTables returns the tables of the migration scope: ordinary and partitioned tables of the
// selected schemas, minus system schemas, temporary tables, extension members and the tables
// excluded by the filter.
func ListTables(ctx context.Context, q pg.Querier, filter *config.Filter) ([]Table, error) {
	var schemas any // NULL means "every schema"
	if len(filter.IncludeSchemas) > 0 {
		schemas = filter.IncludeSchemas
	}
	rows, err := q.Query(ctx, listTablesSQL, schemas)
	if err != nil {
		return nil, fmt.Errorf("list tables: %w", err)
	}
	defer rows.Close()

	var tables []Table
	for rows.Next() {
		var (
			t                               Table
			oid                             int64
			kind, persistence, replicaIdent string
		)
		if err := rows.Scan(&oid, &t.Schema, &t.Name, &kind, &t.IsPartition, &persistence, &replicaIdent,
			&t.HasPK, &t.HasReplicaIndex, &t.EstimatedRows, &t.TotalBytes); err != nil {
			return nil, fmt.Errorf("scan table row: %w", err)
		}
		t.OID = uint32(oid)
		t.Kind, t.Persistence, t.ReplicaIdent = kind[0], persistence[0], replicaIdent[0]
		if filter.Match(t.Schema, t.Name) {
			tables = append(tables, t)
		}
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("list tables: %w", err)
	}
	return tables, nil
}

const loadColumnsSQL = `
SELECT a.attrelid::bigint,
       a.attname,
       a.atttypid::bigint,
       format_type(a.atttypid, a.atttypmod),
       a.attgenerated::text,
       a.attidentity::text,
       a.attnotnull
FROM pg_attribute a
WHERE a.attrelid = ANY ($1::oid[])
  AND a.attnum > 0
  AND NOT a.attisdropped
ORDER BY a.attrelid, a.attnum`

// LoadColumns fills Table.Columns of every table with one catalog round trip.
func LoadColumns(ctx context.Context, q pg.Querier, tables []Table) error {
	if len(tables) == 0 {
		return nil
	}
	index := make(map[uint32]int, len(tables))
	oids := make([]uint32, len(tables))
	for i := range tables {
		index[tables[i].OID] = i
		oids[i] = tables[i].OID
		tables[i].Columns = nil
	}

	rows, err := q.Query(ctx, loadColumnsSQL, oids)
	if err != nil {
		return fmt.Errorf("load columns: %w", err)
	}
	defer rows.Close()
	for rows.Next() {
		var (
			relOID, typOID   int64
			c                Column
			generated, ident string
		)
		if err := rows.Scan(&relOID, &c.Name, &typOID, &c.TypeName, &generated, &ident, &c.NotNull); err != nil {
			return fmt.Errorf("scan column row: %w", err)
		}
		c.TypeOID = uint32(typOID)
		if generated != "" {
			c.Generated = generated[0]
		}
		if ident != "" {
			c.Identity = ident[0]
		}
		i, ok := index[uint32(relOID)]
		if !ok {
			continue
		}
		tables[i].Columns = append(tables[i].Columns, c)
	}
	return rows.Err()
}
